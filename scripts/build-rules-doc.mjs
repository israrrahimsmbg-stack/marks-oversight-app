#!/usr/bin/env node
// Regenerates the rules table in docs/COMPLIANCE_RULES.md from config/rules.json.
import { readFileSync, writeFileSync } from "node:fs";

const START = "<!-- RULES:START (generated by `npm run rules:doc`; edit config/rules.json, not this table) -->";
const END = "<!-- RULES:END -->";

export function rulesTable(config) {
  const iv = i => `${i.n} ${i.unit}${i.n === 1 ? "" : "s"}`;
  const esc = s => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
  const rows = config.rules.map(r => {
    const d = { ...config.defaults, ...r };
    const src = r.source_url ? `[link](${r.source_url})` : "–";
    return `| \`${r.key}\` | ${esc(r.label)} | ${r.kind} | ${iv(r.interval)} | ${d.amber_days}d | ${d.kind === "recurring" ? d.grace_days + "d" : "–"} | ${d.escalate_manager_days}d / ${d.escalate_head_office_days}d | **${r.basis}** | ${esc(r.legal_ref)} ${src} | ${esc(r.duty_holder)} | ${esc(r.notes)} | ${r.status}${r.verified_by ? ` (${esc(r.verified_by)})` : ""} · checked ${r.last_checked} |`;
  });
  return [
    START,
    "| Key | Item | Kind | Interval / validity | Amber window | Grace | Escalate (manager / head office) | Basis | Legal reference and source | Duty holder | Notes | Status |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ...rows,
    END,
  ].join("\n");
}

export function injectTable(doc, table) {
  const a = doc.indexOf(START), b = doc.indexOf(END);
  if (a < 0 || b < 0) throw new Error("Markers missing in COMPLIANCE_RULES.md");
  return doc.slice(0, a) + table + doc.slice(b + END.length);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const cfg = JSON.parse(readFileSync(new URL("../config/rules.json", import.meta.url)));
  const path = new URL("../docs/COMPLIANCE_RULES.md", import.meta.url);
  writeFileSync(path, injectTable(readFileSync(path, "utf8"), rulesTable(cfg)));
  console.log(`✓ docs/COMPLIANCE_RULES.md: ${cfg.rules.length} rules`);
}
